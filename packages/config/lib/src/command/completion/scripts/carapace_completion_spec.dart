/// Generates a Carapace spec for [executableName].
///
/// The spec bridges to the `__complete` request of the executable via
/// Carapace's Cobra bridge (the request protocol is the same),
/// so it needs to be installed only once in the Carapace specs directory.
/// See https://carapace-sh.github.io/carapace-bin/spec.html.
String carapaceCompletionSpec(
  final String executableName, {
  final String? description,
}) {
  final summary = description?.trim().split('\n').first.trim();
  final buffer = StringBuffer()
    ..writeln('# carapace spec for $executableName')
    ..writeln('#')
    ..writeln(
      '# Generated by `$executableName completion carapace`. Install once by '
      'saving it as',
    )
    ..writeln('#   <carapace specs directory>/$executableName.yaml')
    ..writeln(
      '# where the specs directory is shown by `carapace --help`, for example',
    )
    ..writeln(
      '# ~/.config/carapace/specs on Linux and '
      '~/Library/Application Support/carapace/specs on macOS.',
    )
    ..writeln('#')
    ..writeln(
      '# The spec contains no commands or options. Carapace asks the executable',
    )
    ..writeln(
      '# for the completion alternatives (`$executableName __complete ...`), '
      'so it keeps',
    )
    ..writeln('# working when the executable is updated.')
    ..writeln('name: ${_yamlString(executableName)}');
  if (summary != null && summary.isNotEmpty) {
    buffer.writeln('description: ${_yamlString(summary)}');
  }
  buffer
    ..writeln('parsing: disabled')
    ..writeln('completion:')
    ..writeln('  positionalany:')
    ..writeln(
      '    - ${_yamlString('\$carapace.bridge.Cobra([$executableName])')}',
    );
  return buffer.toString();
}

/// A double-quoted YAML scalar.
String _yamlString(final String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll('"', r'\"')
      .replaceAll('\n', r'\n');
  return '"$escaped"';
}
