import 'scripts/bash_completion_script.dart';
import 'scripts/carapace_completion_spec.dart';
import 'scripts/fish_completion_script.dart';
import 'scripts/powershell_completion_script.dart';
import 'scripts/zsh_completion_script.dart';

/// The shells and completion frameworks for which completion scripts
/// can be generated.
enum CompletionShell {
  bash('Bash'),
  zsh('Zsh'),
  fish('Fish'),
  powershell('PowerShell'),
  carapace('Carapace');

  /// The display name.
  final String displayName;

  const CompletionShell(this.displayName);

  /// Generates the completion script (or spec) for [executableName].
  ///
  /// The script is independent of the commands and options of the
  /// executable: it asks the executable for the completion alternatives
  /// via the `__complete` request, so it needs to be installed only once.
  ///
  /// [description] is a short description of the executable, included
  /// where the format supports it.
  ///
  /// [viaOption] selects how the script is requested from the executable in
  /// the installation instructions of the script header: with the
  /// `completion <shell>` command (the default) or, for an executable
  /// without subcommands, with the `--completion <shell>` option.
  ///
  /// [commandName] makes the script complete that command name instead of
  /// [executableName], for a wrapper script that forwards to the executable
  /// and has the same commands and options. The completion requests are
  /// then sent to [executableName] directly, bypassing the wrapper.
  String script(
    final String executableName, {
    final String? description,
    final bool viaOption = false,
    final String? commandName,
  }) {
    final name = commandName ?? executableName;
    final header = scriptHeader(
      executableName,
      viaOption: viaOption,
      commandName: commandName,
    );
    // Requests go to the command as typed on the command line, unless the
    // script is for a wrapper: then they go to the executable directly.
    final program = name == executableName ? null : executableName;
    return switch (this) {
      CompletionShell.bash => bashCompletionScript(
        name,
        header,
        program: program,
      ),
      CompletionShell.zsh => zshCompletionScript(
        name,
        header,
        program: program,
      ),
      CompletionShell.fish => fishCompletionScript(
        name,
        header,
        program: program,
      ),
      CompletionShell.powershell => powershellCompletionScript(
        name,
        header,
        program: program,
      ),
      CompletionShell.carapace => carapaceCompletionSpec(
        name,
        header,
        program: executableName,
        description: description,
      ),
    };
  }

  /// The command line that prints the completion script for this shell:
  /// `<exe> completion <shell>`, or `<exe> --completion <shell>` if
  /// [viaOption]. With a [commandName], the `completion` command's
  /// `--command <name>` option is added.
  String scriptCommand(
    final String executableName, {
    final bool viaOption = false,
    final String? commandName,
  }) {
    final command = viaOption ? '--completion' : 'completion';
    final forCommand = commandName == null || viaOption
        ? ''
        : ' --command $commandName';
    return '$executableName $command $name$forCommand';
  }

  /// The comment lines for the header of the generated script: what
  /// generated it, how to install it ([installInstructions]) and why it
  /// needs to be installed only once.
  String scriptHeader(
    final String executableName, {
    final bool viaOption = false,
    final String? commandName,
  }) {
    final exe = executableName;
    final name = commandName ?? exe;
    final lines = [
      'Generated by `${scriptCommand(exe, viaOption: viaOption, commandName: commandName)}`.',
      ...installInstructions(
        exe,
        viaOption: viaOption,
        commandName: commandName,
      ).split('\n'),
      '',
      'The script contains no commands or options. The completion alternatives',
      if (name == exe)
        'are requested from the executable (`$exe __complete ...`), so it keeps'
      else
        'are requested from $exe directly (`$exe __complete ...`), so it keeps',
      'working when the executable is updated.',
    ];
    return lines.map((final l) => l.isEmpty ? '#' : '# $l').join('\n');
  }

  /// The command that installs the completion script for this shell,
  /// e.g. `source <(mycli completion bash)`.
  ///
  /// See [installLocation] for where to run or add it,
  /// and [scriptCommand] for [viaOption] and [commandName].
  String installCommand(
    final String executableName, {
    final bool viaOption = false,
    final String? commandName,
  }) {
    final name = commandName ?? executableName;
    final script = scriptCommand(
      executableName,
      viaOption: viaOption,
      commandName: commandName,
    );
    return switch (this) {
      CompletionShell.bash || CompletionShell.zsh => 'source <($script)',
      CompletionShell.fish => '$script > ~/.config/fish/completions/$name.fish',
      CompletionShell.powershell => '$script | Out-String | Invoke-Expression',
      CompletionShell.carapace =>
        '$script > ~/.config/carapace/specs/$name.yaml',
    };
  }

  /// The shell startup file to add [installCommand] to,
  /// or null if the command is run once instead.
  String? get installLocation => switch (this) {
    CompletionShell.bash => '~/.bashrc',
    CompletionShell.zsh => '~/.zshrc, after compinit',
    CompletionShell.powershell => r'$PROFILE',
    CompletionShell.fish || CompletionShell.carapace => null,
  };

  /// One-line installation instruction for this shell:
  /// the [installCommand], followed by the [installLocation] as a comment.
  String installInstruction(
    final String executableName, {
    final bool viaOption = false,
    final String? commandName,
  }) {
    final command = installCommand(
      executableName,
      viaOption: viaOption,
      commandName: commandName,
    );
    final location = installLocation;
    return location == null ? command : '$command  # in $location';
  }

  /// Longer installation instructions for this shell, including
  /// alternative ways to install the script where available, and how to
  /// activate the installed completion ([activationInstruction]).
  String installInstructions(
    final String executableName, {
    final bool viaOption = false,
    final String? commandName,
  }) {
    final name = commandName ?? executableName;
    final script = scriptCommand(
      executableName,
      viaOption: viaOption,
      commandName: commandName,
    );
    final command = installCommand(
      executableName,
      viaOption: viaOption,
      commandName: commandName,
    );
    final install = switch (this) {
      CompletionShell.bash =>
        'Add to ~/.bashrc:\n'
            '  $command\n'
            'or save it once:\n'
            '  $script > /etc/bash_completion.d/$name',
      CompletionShell.zsh =>
        'Add to ~/.zshrc (after compinit):\n'
            '  $command\n'
            'or save it once to a directory in \$fpath:\n'
            '  $script > "\${fpath[1]}/_$name"',
      CompletionShell.fish => 'Save it once:\n  $command',
      CompletionShell.powershell =>
        'Add to your PowerShell profile (\$PROFILE):\n  $command',
      CompletionShell.carapace =>
        'Save it once to the Carapace specs directory '
            '(shown by `carapace --help`):\n'
            '  $command\n'
            '(macOS: ~/Library/Application Support/carapace/specs/$name.yaml)',
    };
    return '$install\n$activationInstruction';
  }

  /// How to make a newly installed completion take effect in the current
  /// shell session, e.g. by reloading the shell.
  String get activationInstruction => switch (this) {
    CompletionShell.bash => 'Then reload the shell:\n  exec bash',
    CompletionShell.zsh =>
      'Then reload the shell:\n'
          '  exec zsh\n'
          '(when saved to \$fpath, first remove ~/.zcompdump* '
          'to rebuild the completion cache)',
    CompletionShell.fish => 'Fish loads it automatically, no reload needed.',
    CompletionShell.powershell => 'Then reload the profile:\n  . \$PROFILE',
    CompletionShell.carapace => 'Then start a new shell session.',
  };
}

/// Short installation instructions for all shells, one line per shell,
/// under an `Installation:` heading. Used in the usage of the
/// `completion` command.
String completionInstallationOverview(
  final String executableName, {
  final bool viaOption = false,
}) {
  const labelWidth = 12;
  return [
    'Installation:',
    for (final shell in CompletionShell.values)
      '  ${'${shell.displayName}:'.padRight(labelWidth)} '
          '${shell.installInstruction(executableName, viaOption: viaOption)}',
  ].join('\n');
}

/// A name for [executableName] that is safe to use in shell identifiers:
/// letters, digits and underscores only.
String shellIdentifier(final String executableName) {
  final sanitized = executableName.replaceAll(RegExp(r'[^A-Za-z0-9_]'), '_');
  if (sanitized.isEmpty || RegExp(r'^[0-9]').hasMatch(sanitized)) {
    return '_$sanitized';
  }
  return sanitized;
}

/// [value] as a single-quoted string literal for POSIX shells and Fish.
String shellQuote(final String value) {
  return "'${value.replaceAll("'", r"'\''")}'";
}
